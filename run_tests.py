DOC_RE = re.compile(r"^(TC-\d+)[:\s]", re.I)


def describe(test):
    """Pull the TC id and a readable name out of a test method."""
    name = test._testMethodName
    m = re.match(r"test_(tc\d+)_(.+)", name)
    if not m:
        return name.upper(), name.replace("_", " ")
    tc = m.group(1).upper().replace("TC", "TC-")
    return tc, m.group(2).replace("_", " ")


def main():
    loader = unittest.TestLoader()
    suite = loader.discover(os.path.join(HERE, "tests"), top_level_dir=HERE)

    cases = []
    for group in suite:
        for sub in group:
            for test in sub:
                cases.append(test)

    stream = io.StringIO()
    runner = unittest.TextTestRunner(stream=stream, verbosity=0)
    result = runner.run(suite)

    failed_ids = set()
    for test, _ in list(result.failures) + list(result.errors):
        failed_ids.add(describe(test)[0])

    rows = []
    for test in sorted(cases, key=lambda t: describe(t)[0]):
        tc, what = describe(test)
        doc = (test._testMethodDoc or "").strip().split("\n")[0]
        status = "FAIL" if tc in failed_ids else "PASS"
        rows.append({
            "id": tc,
            "input": what,
            "expected": doc or "Behaviour holds as specified",
            "actual": "As expected" if status == "PASS" else "Did not match",
            "status": status,
            "remarks": test.__class__.__name__,
        })

    os.makedirs(OUT, exist_ok=True)
    payload = {
        "automated": rows,
        "defects": DEFECT_LOG,
        "total": result.testsRun,
        "failures": len(result.failures) + len(result.errors),
    }
    with open(os.path.join(OUT, "test_report.json"), "w") as f:
        json.dump(payload, f, indent=2)

    write_markdown(payload)

    line = "=" * 74
    print(line)
    print("OUROBOROS  Test suite")
    print(line)
    print(f"Automated cases run : {result.testsRun}")
    print(f"Passed              : {result.testsRun - payload['failures']}")
    print(f"Failed              : {payload['failures']}")
    print(f"Defects logged      : {len([d for d in DEFECT_LOG if d['status'] == 'FAIL'])} "
          f"found, {len([d for d in DEFECT_LOG if d['status'] == 'PASS'])} resolved")
    print()
    print("Written:")
    print("  outputs/test_report.json")
    print("  outputs/TEST_CASES.md")
    print(line)
    return 0 if payload["failures"] == 0 else 1


def write_markdown(payload):
    lines = ["# Test Case Documentation", "",
             "Generated by `run_tests.py`. Do not edit by hand.", "",
             f"**Automated cases:** {payload['total']} run, "
             f"{payload['total'] - payload['failures']} passed, "
             f"{payload['failures']} failed.", "",
             "## Defects found, fixed and retested", "",
             "| Test Case ID | Input | Expected Output | Actual Output | Status | Remarks |",
             "|---|---|---|---|---|---|"]
    for d in payload["defects"]:
        lines.append(f"| **{d['id']}** | {d['input']} | {d['expected']} | "
                     f"{d['actual']} | **{d['status']}** | {d['remarks']} |")

    lines += ["", "## Automated test cases", "",
              "| Test Case ID | What is tested | Expected Output | Actual Output | Status |",
              "|---|---|---|---|---|"]
    for r in payload["automated"]:
        lines.append(f"| {r['id']} | {r['input']} | {r['expected']} | "
                     f"{r['actual']} | {r['status']} |")

    with open(os.path.join(OUT, "TEST_CASES.md"), "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    raise SystemExit(main())
